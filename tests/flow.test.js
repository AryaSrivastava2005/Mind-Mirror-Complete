const answers = Object.fromEntries(Array.from({length:15}, (_,i)=>['q'+(i+1),'3']));
test('scores, ties, and invalid submissions', () => {
  const r=calculateResult(answers);
  assert.equal(r.totalScore,45); assert.equal(r.topCategories.length,5);
  assert.equal(validateAnswers(answers),true);
  assert.equal(validateAnswers({...answers,q1:'99'}),false);
  assert.equal(validateAnswers({...answers,q1:['3']}),false);
  assert.equal(validateAnswers({}),false);
});
